/* Scripted answers used when AI_MOCK=1 (local testing without an API key). */
export function mockStructure(sections: Array<{ title: string }>, onlyRemaining: boolean): string[] {
  const lines: string[] = [];
  if (!onlyRemaining) lines.push(JSON.stringify({ meta: { title: "Mock structured report", subtitle: "Generated by AI_MOCK for testing" } }));
  sections.forEach((s, i) => lines.push(JSON.stringify({ title: s.title, blocks: i === 0
    ? [{ t: "stats", items: [{ value: "1,240", label: "project-affected persons" }, { value: "18.4 km", label: "road length" }] }, { t: "p", text: "Mock paragraph drawn from the **draft**." }]
    : [{ t: "callout", title: "To be completed", text: `Add content for ${s.title}.` }] })));
  // Split into small chunks so streaming is exercised.
  return lines.join("\n").match(/[\s\S]{1,60}/g) || [];
}
export function mockRefine(section: any, instruction: string) {
  return JSON.stringify({ title: section.title, blocks: [...(section.blocks || []), { t: "p", text: `Mock refinement: ${instruction}` }] });
}
